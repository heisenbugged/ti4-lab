/**
 * Scans every finished draft and writes src/data/sliceValueDistribution.ts:
 * per format family, the percentiles of slice-set averages and of single
 * slice values. Run against a prod backup (`npm run db:backup`):
 *
 *   tsx scripts/slice-value-distribution.ts ~/Downloads/ti4-lab_13_10_2026.db
 */
import Database from "better-sqlite3";
import { writeFileSync } from "fs";
import { draftConfig } from "~/draft";
import { sliceValueFamily, type SliceValueFamily } from "~/data/sliceValueFamilies";
import { calculateSliceValue, draftSliceValueConfig } from "~/stats";
import type { Draft, DraftType } from "~/types";
import { systemsInSlice } from "~/utils/slice";

const dbPath = process.argv[2] ?? "sqlite.db";
const outPath = "src/data/sliceValueDistribution.ts";
const db = new Database(dbPath, { readonly: true, fileMustExist: true });

const samples: Partial<Record<SliceValueFamily, { averages: number[]; slices: number[] }>> = {};
let skipped = 0;

const rows = db.prepare("SELECT data FROM drafts WHERE isComplete = 1").iterate() as Iterable<{ data: Buffer | string }>;
for (const row of rows) {
  try {
    const draft = JSON.parse(row.data.toString()) as Draft;
    const type = draft.settings?.type as DraftType;
    const family = sliceValueFamily(type);
    if (!family || !draft.slices?.length) continue;
    const valueConfig = draftSliceValueConfig(
      draftConfig[type],
      draft.settings.sliceGenerationConfig?.sliceValueModifiers,
    );
    const values = draft.slices.map((slice) => calculateSliceValue(systemsInSlice(slice), valueConfig));
    if (!values.every(Number.isFinite)) throw new Error("bad value");
    const bucket = (samples[family] ??= { averages: [], slices: [] });
    bucket.averages.push(values.reduce((sum, v) => sum + v, 0) / values.length);
    bucket.slices.push(...values);
  } catch {
    skipped++;
  }
}

/** 101 values: the 0th to 100th percentile. */
function percentiles(values: number[]) {
  const sorted = [...values].sort((a, b) => a - b);
  return Array.from({ length: 101 }, (_, p) => {
    const value = sorted[Math.round((p / 100) * (sorted.length - 1))];
    return Math.round(value * 100) / 100;
  });
}

const families = Object.fromEntries(
  Object.entries(samples).map(([family, { averages, slices }]) => [
    family,
    { drafts: averages.length, averages: percentiles(averages), slices: percentiles(slices) },
  ]),
);

writeFileSync(
  outPath,
  `// Generated by scripts/slice-value-distribution.ts from finished drafts. Do not edit.
import type { SliceValueDistribution } from "./sliceValueFamilies";

export const SLICE_VALUE_DISTRIBUTION: SliceValueDistribution = {
  generatedAt: "${new Date().toISOString().slice(0, 10)}",
  families: {
${Object.entries(families)
  .map(
    ([family, { drafts, averages, slices }]) => `    ${family}: {
      drafts: ${drafts},
      averages: [${averages.join(", ")}],
      slices: [${slices.join(", ")}],
    },`,
  )
  .join("\n")}
  },
};
`,
);

for (const [family, { drafts, averages }] of Object.entries(families)) {
  console.log(`${family.padEnd(8)} ${String(drafts).padStart(6)} drafts, median set average ${averages[50]}`);
}
console.log(`skipped ${skipped}, wrote ${outPath}`);
